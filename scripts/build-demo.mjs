#!/usr/bin/env node
/**
 * Bundle the browser demo.
 *
 * `linebreak` is published as ESM with bare specifiers (`import x from
 * "unicode-trie"`), so a browser cannot load it directly and a bundling step is
 * unavoidable. esbuild is used only as a dev dependency; the library itself has no
 * build step for Node consumers.
 *
 * The bundle is written to demo/hanjustify.bundle.js and committed, so the demo page
 * works from a plain static file server (and from GitHub Pages) without npm.
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outfile = join(root, 'demo/hanjustify.bundle.js');

await build({
  entryPoints: [join(root, 'demo/entry.mjs')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2020'],
  legalComments: 'inline',
  banner: {
    js: '/* GENERATED by scripts/build-demo.mjs — do not edit. */',
  },
});

const buf = readFileSync(outfile);
const sha = createHash('sha256').update(buf).digest('hex');
const { size } = statSync(outfile);
console.log(`wrote demo/hanjustify.bundle.js  ${(size / 1024).toFixed(1)} KiB  sha256=${sha}`);
